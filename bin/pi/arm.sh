#!/usr/bin/env bash
# arm.sh — the Gná arm, honestly: what the watch is, and whether THIS harness can arm it.
#
#   arm.sh status                  # the unit, the heartbeat, the lock — the truth about arming
#   arm.sh hook <harness>          # the session-start hook a harness with hooks must install
#   arm.sh hook hermes --install   # install it (idempotent: config + consent allowlist)
#   arm.sh hook hermes --check     # exit 1 unless it is installed AND consented
#
# The watch LOOP is harness-agnostic (the ymir-syn-watch unit + bin/pi/syn-watch-arm.sh);
# the SESSION SIDE (relaying a wake into a live session) is owned by a harness extension:
# Pi (gna-pi-watch) and OpenCode (syn-watch-arm.js) have one. Hermes has no extension API for
# a live session but it has a real shell-hook surface (`hooks:` in ~/.hermes/config.yaml,
# `hermes hooks`) — so its session side is bin/seat/hermes-session-hook.sh, installed here.
# A harness with no hook and no extension cannot be armed — and this door says so instead of
# pretending (plan 177 H4).
set -uo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

# A worktree is removed by `yggdrasil.sh cleanup`, so a hook pointing into one dangles for every
# later session — the same transient-root fault the AGENTS.md contract learned (2026-10-24). The
# installed hook is therefore a STABLE shim at ~/.hermes/agent-hooks/ (Hermes' own convention: keep
# hook scripts where they are easy to audit) that resolves the house at RUN time and execs the door
# in bin/. The command string never changes, so consent recorded once stays valid across updates.
seat_root() {
  local r
  while IFS= read -r r; do
    [ -n "$r" ] || continue
    [ -x "$r/bin/seat/hermes-session-hook.sh" ] && { printf '%s' "$r"; return 0; }
  done < <(head -n 5 "$HOME/.pi/agent/extensions/.ymir-root" 2>/dev/null)
  printf '%s' "$ROOT"
}

hermes_hook_shim() { printf '%s' "${HERMES_SHIM:-$HOME/.hermes/agent-hooks/ymir-session-hook.sh}"; }
hermes_hook_command() { hermes_hook_shim; }

hermes_config() { printf '%s' "${HERMES_CONFIG:-$HOME/.hermes/config.yaml}"; }
hermes_allowlist() { printf '%s' "${HERMES_ALLOWLIST:-$HOME/.hermes/shell-hooks-allowlist.json}"; }

hermes_installed() {  # 0 when the exact command is already in the config
  local cfg cmd; cfg="$(hermes_config)"; cmd="$(hermes_hook_command)"
  [ -r "$cfg" ] && grep -qF "command: $cmd" "$cfg"
}

hermes_shim() {  # write the stable shim (idempotent: identical content is left untouched)
  local shim fallback body tmp
  shim="$(hermes_hook_shim)"; fallback="$(seat_root)"
  body="$(sed "s|@FALLBACK@|$fallback|" <<'SHIM'
#!/usr/bin/env bash
# generated by bin/pi/arm.sh hook hermes --install — do not edit; re-run the door instead.
# Resolve the house at RUN time, then exec its own session door (the behaviour lives in bin/).
# `.ymir-root` may hold several roots (a pinned runtime beside the tree), so every candidate is
# tried in order and a missing door is a NAMED skip with a valid no-op on stdout — never a crash.
set -uo pipefail
fallback=@FALLBACK@
try() {
  [ -n "${1:-}" ] || return 1
  [ -x "$1/bin/seat/hermes-session-hook.sh" ] || return 1
  exec bash "$1/bin/seat/hermes-session-hook.sh"
}
[ -n "${YMIR_ROOT:-}" ] && try "$YMIR_ROOT"
while IFS= read -r root; do try "$root"; done < <(head -n 5 "$HOME/.pi/agent/extensions/.ymir-root" 2>/dev/null)
try "$fallback"
printf 'hermes-session-hook: no door in %s — re-arm: bin/pi/arm.sh hook hermes --install\n' \
  "${YMIR_ROOT:-${fallback}}" >&2
printf '{}\n'
SHIM
)"
  [ -f "$shim" ] && [ "$(cat "$shim")" = "$body" ] && { printf 'hermes: shim already current (%s)\n' "$shim"; return 0; }
  mkdir -p "$(dirname "$shim")"
  tmp="$shim.tmp"
  printf '%s\n' "$body" > "$tmp" && chmod 755 "$tmp" && mv "$tmp" "$shim" \
    || { printf 'hermes: could not write %s\n' "$shim" >&2; return 1; }
  printf 'hermes: shim written (%s), resolving the house at run time\n' "$shim"
}

hermes_consented() {  # 0 when both (event, command) pairs are in the allowlist
  local al cmd; al="$(hermes_allowlist)"; cmd="$(hermes_hook_command)"
  [ -r "$al" ] || return 1
  python3 - "$al" "$cmd" <<'PY'
import json, sys
al, cmd = sys.argv[1], sys.argv[2]
try:
    d = json.load(open(al))
except Exception:
    raise SystemExit(1)
have = {(e.get("event"), e.get("command")) for e in (d.get("approvals") or []) if isinstance(e, dict)}
raise SystemExit(0 if {("on_session_start", cmd), ("pre_llm_call", cmd)} <= have else 1)
PY
}

hermes_print_hook() {
  local cmd; cmd="$(hermes_hook_command)"
  printf 'hermes: the session side is a SHELL HOOK (~/.hermes/config.yaml `hooks:`, `hermes hooks`).\n'
  printf '        the script: bin/seat/hermes-session-hook.sh — the Sága digest at session start\n'
  printf '        (on_session_start), delivered into the first turn (pre_llm_call), only inside the house.\n'
  printf 'install: bin/pi/arm.sh hook hermes --install      check: bin/pi/arm.sh hook hermes --check\n\n'
  printf 'hooks:\n'
  printf '  on_session_start:\n    - command: %s\n      timeout: 180\n' "$cmd"
  printf '  pre_llm_call:\n    - command: %s\n      timeout: 60\n' "$cmd"
  printf '\nconsent (each pair, once): %s\n' "$(hermes_allowlist)"
  printf '  {"approvals":[{"event":"on_session_start","command":"%s"},\n' "$cmd"
  printf '                {"event":"pre_llm_call","command":"%s"}]}\n' "$cmd"
}

hermes_install() {
  local cfg cmd al mtime
  command -v hermes >/dev/null 2>&1 || { printf 'hermes: not installed on this seat — nothing to arm (clean skip)\n'; return 0; }
  cfg="$(hermes_config)"; al="$(hermes_allowlist)"
  [ -x "$ROOT/bin/seat/hermes-session-hook.sh" ] || { printf 'hermes: the hook door is missing at %s\n' "$ROOT/bin/seat/hermes-session-hook.sh" >&2; return 1; }
  hermes_shim || return 1
  cmd="$(hermes_hook_command)"
  [ -x "$cmd" ] || { printf 'hermes: the shim is not executable at %s\n' "$cmd" >&2; return 1; }

  if hermes_installed; then
    printf 'hermes: hook already installed (%s)\n' "$cfg"
  elif [ -r "$cfg" ] && grep -qE '^hooks:' "$cfg"; then
    # Appending a second top-level `hooks:` key would silently shadow the first (YAML last-wins),
    # so this door refuses and prints the exact block instead of mangling a file the operator owns.
    printf 'hermes: %s ALREADY has a hooks: block and ours is not in it — not touching it.\n' "$cfg" >&2
    printf '        add these two entries by hand (exact text, one command, two events):\n\n' >&2
    hermes_print_hook >&2
    return 1
  else
    mkdir -p "$(dirname "$cfg")"
    { printf '\n# Added by bin/pi/arm.sh (plan 177 H4) — the Gná arm session side for Hermes.\n'
      printf '# Remove this block to unarm. Consent pairs live in shell-hooks-allowlist.json.\n'
      printf 'hooks:\n'
      printf '  on_session_start:\n    - command: %s\n      timeout: 180\n' "$cmd"
      printf '  pre_llm_call:\n    - command: %s\n      timeout: 60\n' "$cmd"
    } >> "$cfg"
    printf 'hermes: hooks block appended to %s (append-only; no existing key rewritten)\n' "$cfg"
  fi

  # Consent is (event, command)-keyed, and Hermes keys it on the command STRING — but it also flags
  # mtime drift so a human can decide whether to re-approve. Re-arming rewrites the shim, so the
  # recorded mtime is refreshed here; the decision to run this command stays the one already made.
  mkdir -p "$(dirname "$al")"
  mtime="$(python3 -c 'import os,sys,datetime;print(datetime.datetime.fromtimestamp(os.path.getmtime(sys.argv[1]),tz=datetime.timezone.utc).isoformat().replace("+00:00","Z"))' "$cmd" 2>/dev/null || true)"
  python3 - "$al" "$cmd" "$mtime" <<'PY'
import json, os, sys
from datetime import datetime, timezone
al, cmd, mtime = sys.argv[1], sys.argv[2], sys.argv[3]
try:
    d = json.load(open(al))
    if not isinstance(d, dict):
        d = {}
except Exception:
    d = {}
now = datetime.now(tz=timezone.utc).isoformat().replace("+00:00", "Z")
kept = [e for e in (d.get("approvals") or [])
        if not (isinstance(e, dict) and e.get("command") == cmd)]
for ev in ("on_session_start", "pre_llm_call"):
    entry = {"event": ev, "command": cmd, "approved_at": now}
    if mtime:
        entry["script_mtime_at_approval"] = mtime
    kept.append(entry)
d["approvals"] = kept
with open(al + ".arm.tmp", "w") as fh:
    json.dump(d, fh, indent=2, sort_keys=True)
os.replace(al + ".arm.tmp", al)
print("hermes: %d consent pair(s) recorded in %s" % (len(kept), al))
PY

  command -v hermes >/dev/null 2>&1 && hermes hooks list 2>&1 | sed -n '1,12p'
  return 0
}

hermes_check() {
  command -v hermes >/dev/null 2>&1 || { printf 'hermes: not installed on this seat — nothing to check (clean skip)\n'; return 0; }
  local bad=0 shim
  shim="$(hermes_hook_shim)"
  [ -x "$shim" ] && printf 'hermes: shim present ✓\n' || { printf 'hermes: shim MISSING at %s — bin/pi/arm.sh hook hermes --install\n' "$shim"; bad=1; }
  hermes_installed && printf 'hermes: hook installed ✓\n' || { printf 'hermes: hook NOT installed — bin/pi/arm.sh hook hermes --install\n'; bad=1; }
  hermes_consented && printf 'hermes: consent recorded ✓\n' || { printf 'hermes: consent NOT recorded — install records it, or approve on the first run\n'; bad=1; }
  if [ -x "$shim" ]; then
    local first_root
    first_root="$(head -n1 "$HOME/.pi/agent/extensions/.ymir-root" 2>/dev/null || true)"
    if [ -n "$first_root" ] && [ ! -x "$first_root/bin/seat/hermes-session-hook.sh" ]; then
      printf 'hermes: %s carries no session door YET — the shim names that skip and answers {} until the door lands there\n' "$first_root"
    fi
  fi
  return "$bad"
}

case "${1:-status}" in
  -h|--help) sed -n '2,14p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
  status)
    # no session bus is not "absent": say unknown, so a wrong claim never closes the question
    if [ -z "${XDG_RUNTIME_DIR:-}" ] && [ -z "${DBUS_SESSION_BUS_ADDRESS:-}" ]; then
      unit="unknown (no session bus in this context)"
    else
      unit="$(systemctl --user is-active ymir-syn-watch.service 2>/dev/null || echo absent)"
    fi
    printf 'arm[3]{what,value,note}:\n'
    printf '  "watch unit","%s","the loop runs outside the session"\n' "$unit"
    printf '  "lock","%s","the session that holds the helm"\n' "$(cat "$HOME/.pi/agent/extensions/.lock" 2>/dev/null || printf 'none')"
    case "$(uname -s)" in *) : ;; esac
    if [ "$unit" = active ]; then printf '  "arm","possible","the session side is an extension (Pi: gna-pi-watch; OpenCode: syn-watch-arm.js) or a hook (Hermes: arm.sh hook hermes --install)"\n'
    else printf '  "arm","not possible — the watch loop is not running","start ymir-syn-watch.service"\n'; fi ;;
  hook)
    h="${2:-}"; action="${3:-}"
    case "$h" in
      hermes) case "$action" in
                --install|install) hermes_install; exit $? ;;
                --check|check) hermes_check; exit $? ;;
                *) hermes_print_hook; exit 0 ;;
              esac ;;
      claude) printf 'claude: add a SessionStart hook in ~/.claude/settings.json that runs: %s/bin/time/saga-session-start.sh\n' "$ROOT"
              printf '        (this door does not write another harness'"'"'s settings file; the entry is yours to seat)\n' ;;
      codex|cursor) printf '%s: NO session-start hook surface is installed here — it cannot be armed mid-session, and this door says so rather than faking it.\n' "$h"
              printf '        what it CAN do: run %s/bin/time/saga-session-start.sh itself, and ask bin/pi/arm.sh status (or the ymir_arm MCP door) whether the loop is alive.\n' "$ROOT"
              printf '        a harness with no hook and no extension is named, never claimed (plan 177 H4).\n' ;;
      *) printf 'usage: arm.sh hook <hermes [--install|--check] | claude | codex | cursor>\n' ;;
    esac ;;
  *) printf 'error: unknown action %s\nhelp: arm.sh [status|hook <harness>]\n' "$1" >&2; exit 2 ;;
esac
