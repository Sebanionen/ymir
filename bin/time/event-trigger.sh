#!/usr/bin/env bash
# event-trigger.sh — the one door that starts a smithy without a person typing.
#
# A smithy is started by a human, by the clock, or by an event. All three are the
# same two facts — WHO may start it (`trigger:` in its own config) and WHAT is
# launched (its chain and its request) — so all three go through this door. A
# second launcher is how a schedule and a launcher come to disagree.
#
#   bin/time/event-trigger.sh <event-name> [--payload FILE] [--dry-run]
#   bin/time/event-trigger.sh --run <config> [--payload FILE] [--dry-run]
#   bin/time/event-trigger.sh --install-cron [--dry-run] [--cron-file PATH] [--create]
#   bin/time/event-trigger.sh --list
#
# The `trigger:` block, in the smithy's own config (the file a run is launched
# with, so there is no second copy to drift):
#
#   trigger:
#     mode: manual                 # manual | cron | event — ABSENT means manual
#     role: dev                    # required for cron; an ungated row runs everywhere
#     cron: "0 6 * * *"            # required for cron
#     timezone: Europe/Stockholm   # optional; the instant is moved to this seat's clock
#     event: nightly-audit         # required for event
#     chain: apps/smidja/smidja_plan_build.py   # what the trigger launches
#     prompt: requests/nightly-audit.md         # or inline text
#
# The trigger block is read in exactly one place (bin/time/event-trigger-resolve.py).
# Nothing arms itself: a config with no `trigger:` is manual, and a config whose
# block names a mode it cannot launch is REFUSED by name, never skipped quietly.
#
# The cron row is never hand-written: `--install-cron` writes it from the configs
# themselves, inside a managed block, and is idempotent — a second run changes
# nothing. It refuses to gate nothing: `mode: cron` without `role:` is a config
# fault, not a row without a gate.
#
# Exit: 0 done (or, with --dry-run, would be) · 1 a refusal or a failed launch · 2 usage.
set -u
VERSION="1.0.0"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="${BROKK_ROOT_OVERRIDE:-$(CDPATH='' cd "$SCRIPT_DIR" && while [ ! -e "$PWD/.pi" ] || [ ! -d "$PWD/RULES" ]; do [ "$PWD" = / ] && break; cd ..; done; pwd)}"
export ROOT
RESOLVER="$SCRIPT_DIR/event-trigger-resolve.py"
TAB=$(printf '\t')

# shellcheck disable=SC1091
. "$ROOT/bin/vault/hoard-lib.sh" 2>/dev/null || true
HOME_R=""
ymir_home_root HOME_R 2>/dev/null || true
if [ -z "${HOME_R:-}" ]; then
  # Never restate where the home is: one resolver, or a refusal that says so.
  printf 'event-trigger: the home is unresolved — bin/vault/hoard-lib.sh could not answer\n' >&2
  exit 1
fi
STATE="${BROKK_STATE_OVERRIDE:-${YMIR_STATE_DIR:-$HOME_R/state}}"
CRON_FILE_DEFAULT="$HOME_R/config/cron.yaml"
LOG_DIR="$STATE/event-trigger"
LEASE_DIR="$STATE/event-trigger/leases"

BEGIN_MARK='# >>> event-trigger — GENERATED by bin/time/event-trigger.sh --install-cron; do not hand-edit'
END_MARK='# <<< event-trigger'

usage() { sed -n '2,39p' "$0" | sed 's/^# \{0,1\}//'; }

DRY=0
PAYLOAD=""
EVENT=""
RUN_CONFIG=""
INSTALL=0
LIST=0
CRON_FILE="$CRON_FILE_DEFAULT"
CREATE=0
POSITIONAL=""

while [ $# -gt 0 ]; do
  case "$1" in
    --dry-run) DRY=1 ;;
    --payload) shift; PAYLOAD="${1-}" ;;
    --payload=*) PAYLOAD="${1#*=}" ;;
    --run) shift; RUN_CONFIG="${1-}" ;;
    --run=*) RUN_CONFIG="${1#*=}" ;;
    --install-cron) INSTALL=1 ;;
    --list|--status) LIST=1 ;;
    --cron-file) shift; CRON_FILE="${1-}" ;;
    --cron-file=*) CRON_FILE="${1#*=}" ;;
    --create) CREATE=1 ;;
    -h|--help) usage; exit 0 ;;
    --version|-v) printf '%s\n' "$VERSION"; exit 0 ;;
    -*) printf 'event-trigger: unknown flag %s\n' "$1" >&2; exit 2 ;;
    *) if [ -z "$POSITIONAL" ]; then POSITIONAL="$1"; else
         printf 'event-trigger: one event name, not two ("%s", "%s")\n' "$POSITIONAL" "$1" >&2; exit 2
       fi ;;
  esac
  shift
done

[ -n "$POSITIONAL" ] && EVENT="$POSITIONAL"

mkdir -p "$LOG_DIR" "$LEASE_DIR" 2>/dev/null || true

if [ "$INSTALL" = 0 ] && [ "$LIST" = 0 ] && [ -z "$EVENT" ] && [ -z "$RUN_CONFIG" ]; then
  usage >&2; exit 2
fi
if [ -n "$PAYLOAD" ] && [ ! -r "$PAYLOAD" ]; then
  printf 'event-trigger: payload "%s" is not readable\n' "$PAYLOAD" >&2
  exit 1
fi
if [ -n "$PAYLOAD" ]; then
  PAYLOAD="$(cd "$(dirname "$PAYLOAD")" && pwd)/$(basename "$PAYLOAD")"
fi

# ── the scan: one row per smithy config, tab separated ────────────────────────
# COLUMNS: config root mode cron timezone event chain prompt role error
scan_rows() {
  if [ ! -r "$RESOLVER" ]; then
    printf 'event-trigger: the resolver is missing at %s\n' "$RESOLVER" >&2
    return 1
  fi
  python3 "$RESOLVER" scan
}

rel_to_root() {  # <path> -> root-relative when it lives under ROOT, else absolute
  case "$1" in
    "$ROOT"/*) printf '%s' "${1#"$ROOT"/}" ;;
    *) printf '%s' "$1" ;;
  esac
}

field() {  # <row> <index> — tab separated; `-` stands for an empty field
  local row=$1 idx=$2 n=0 rest=$1
  while [ "$n" -lt "$idx" ]; do rest=${rest#*"$TAB"}; n=$((n + 1)); done
  printf '%s' "${rest%%"$TAB"*}"
}

# ── the clock: a cron expression reduced to a shape the scheduler speaks ──────
# The scheduler knows HH:MM, @daily, @hourly and @hourly:MM (plan 140). An
# expression it cannot express is REFUSED here rather than installed as a row
# that never fires — that is how a schedule becomes declared-but-dead.
scheduler_shape() {  # <cron> <timezone> -> "HH:MM" | "@hourly:MM", or "" + reason on stdout
  local expr=$1 tz=$2 m h
  set -f
  set -- $expr
  set +f
  [ $# -eq 5 ] || { printf 'a cron expression needs five fields, got %s' "$#"; return 1; }
  m=$1; h=$2
  if [ "$3" != "*" ] || [ "$4" != "*" ] || [ "$5" != "*" ]; then
    printf 'only days "* * *" are expressible — the scheduler fires daily or hourly, never monthly'
    return 1
  fi
  case "$m" in ''|*[!0-9]*) printf 'minute "%s" is not a number' "$m"; return 1 ;; esac
  [ "$m" -le 59 ] || { printf 'minute "%s" is out of range' "$m"; return 1; }

  if [ "$h" != "*" ]; then
    case "$h" in ''|*[!0-9]*) printf 'hour "%s" is neither * nor a number' "$h"; return 1 ;; esac
    [ "$h" -le 23 ] || { printf 'hour "%s" is out of range' "$h"; return 1; }
  fi

  if [ "$tz" = "-" ] || [ -z "$tz" ]; then
    # No zone named: the row is written in this seat's clock, which is the
    # clock the scheduler reads. Nothing to convert.
    if [ "$h" = "*" ]; then printf '@hourly:%02d' "$m"; else printf '%02d:%02d' "$h" "$m"; fi
    return 0
  fi

  # A named zone is honoured by asking for the SAME INSTANT in both clocks. Done
  # by instant rather than by a UTC offset on purpose: an offset taken at epoch
  # is the winter offset, and a 06:00 summer row would fire an hour late.
  local stamp
  local padded; padded=$(printf '%02d:%02d:00' "${h:-0}" "$m")
  if [ "$h" = "*" ]; then
    local hour_there
    hour_there=$(TZ="$tz" date +%H 2>/dev/null) || {
      printf 'timezone "%s" is not a zone this machine knows' "$tz"; return 1; }
    padded=$(printf '%s:%02d:00' "$hour_there" "$m")
    stamp=$(TZ="$tz" date -d "today $padded" +%s 2>/dev/null) || {
      printf 'timezone "%s": the instant could not be resolved' "$tz"; return 1; }
    printf '@hourly:%02d' "$(date -d "@$stamp" +%M)"
    return 0
  fi
  stamp=$(TZ="$tz" date -d "today $padded" +%s 2>/dev/null) || {
    printf 'timezone "%s" is not a zone this machine knows' "$tz"; return 1; }
  printf '%s' "$(date -d "@$stamp" +%H:%M)"
  return 0
}

# ── the launch ────────────────────────────────────────────────────────────────
slug_of() { printf '%s' "$1" | tr -c 'A-Za-z0-9._-' '_' | cut -c1-120; }

# launch <config> <root> <chain> <prompt> <role> <event> <source>
# stdout: "launched<TAB>pid N · log" | "would-run<TAB>cmd" | "refused<TAB>reason"
# return: 0 launched or would-run · 1 refused
launch() {
  local config=$1 root=$2 chain=$3 prompt=$4 role=$5 event=$6 source=$7
  local abs_config abs_chain abs_prompt chain_arg slug lease log held pid uv_bin

  case "$config" in /*) abs_config=$config ;; *) abs_config="$ROOT/$config" ;; esac
  case "$chain" in /*) abs_chain=$chain ;; *) abs_chain="$root/$chain" ;; esac
  if [ ! -r "$abs_chain" ]; then
    printf 'refused\tchain "%s" is not readable (resolved %s)' "$chain" "$abs_chain"; return 1
  fi
  # A request that names a path IS a path, and a path that is not there is a
  # refusal — never quietly sent to the model as if it were a sentence.
  case "$prompt" in
    */*|*.md)
      case "$prompt" in /*) abs_prompt=$prompt ;; *) abs_prompt="$root/$prompt" ;; esac
      if [ ! -r "$abs_prompt" ]; then
        printf 'refused\tprompt "%s" names a path but is not readable (resolved %s)' "$prompt" "$abs_prompt"; return 1
      fi
      ;;
    *) abs_prompt=$prompt ;;
  esac
  chain_arg=$(rel_to_root "$abs_chain")
  uv_bin=$(command -v uv 2>/dev/null || true)

  # A dry run launches nothing, so a lease held by a live run must not stop it:
  # the whole point of --dry-run is to answer "what WOULD this do" while it is busy.
  if [ "$DRY" = 1 ]; then
    printf 'would-run\t%s run %s "%s" --config %s  (cwd %s)' \
      "${uv_bin:-uv}" "$chain_arg" "$abs_prompt" "$(rel_to_root "$abs_config")" "$root"
    return 0
  fi

  slug=$(slug_of "$abs_config")
  lease="$LEASE_DIR/$slug.pid"
  if [ -r "$lease" ]; then
    held=$(tr -d '[:space:]' <"$lease" 2>/dev/null || true)
    case "$held" in
      ''|*[!0-9]*) : ;;
      *) if kill -0 "$held" 2>/dev/null; then
           printf 'refused\tthat smithy is already running (pid %s, lease %s)' "$held" "$lease"; return 1
         fi ;;
    esac
  fi

  log="$LOG_DIR/$(date -u +%Y%m%dT%H%M%SZ)-$(basename "$abs_config" .yaml).log"

  if [ -z "$uv_bin" ]; then
    printf 'refused\tuv is not on PATH — the smithy is a uv single-file script and cannot be launched'
    return 1
  fi

  {
    printf '# event-trigger %s — source=%s event=%s role=%s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$source" "${event:--}" "${role:--}"
    printf '# config=%s\n# chain=%s\n# prompt=%s\n' "$abs_config" "$abs_chain" "$abs_prompt"
    [ -n "$PAYLOAD" ] && printf '# payload=%s (%s bytes)\n' "$PAYLOAD" "$(wc -c <"$PAYLOAD" 2>/dev/null | tr -d ' ')"
  } >"$log"

  # Detached: a cron row must not hold the scheduler's tick for the length of a
  # smithy run. The lease above is what stops two runs of one smithy overlapping.
  (
    cd "$root" || exit 1
    export SMIDJA_EVENT="$event" SMIDJA_TRIGGER_SOURCE="$source" SMIDJA_TRIGGER_ROLE="$role"
    [ -n "$PAYLOAD" ] && export SMIDJA_EVENT_PAYLOAD="$PAYLOAD"
    exec "$uv_bin" run "$chain_arg" "$abs_prompt" --config "$abs_config"
  ) >>"$log" 2>&1 </dev/null &
  pid=$!
  printf '%s\n' "$pid" >"$lease"
  printf 'launched\tpid %s · %s' "$pid" "$log"
  return 0
}

# ── --list: every smithy, and whether anything may start it ───────────────────
if [ "$LIST" = 1 ]; then
  rows=$(scan_rows) || exit 1
  n=0; out=""
  while IFS= read -r row; do
    [ -n "$row" ] || continue
    mode=$(field "$row" 2); cron=$(field "$row" 3); tz=$(field "$row" 4)
    ev=$(field "$row" 5); chain=$(field "$row" 6); role=$(field "$row" 8); err=$(field "$row" 9)
    case "$mode" in
      cron) fires="$cron"; [ "$tz" != "-" ] && fires="$fires $tz"; fires="$fires @$role" ;;
      event) fires="event $ev" ;;
      manual) fires="a person" ;;
      *) fires="-" ;;
    esac
    out="${out}  \"$(rel_to_root "$(field "$row" 0)")\",\"$mode\",\"$fires\",\"$chain\",\"$err\"
"
    n=$((n + 1))
  done <<EOF
$rows
EOF
  printf 'smithies[%s]{config,mode,fires_when,chain,error}:\n%s' "$n" "$out"
  exit 0
fi

# ── --install-cron: write the rows the configs themselves declare ─────────────
if [ "$INSTALL" = 1 ]; then
  rows=$(scan_rows) || exit 1
  block="${BEGIN_MARK}
# Each row below is derived from a config's own trigger block. Change the trigger,
# then re-run --install-cron; editing a row here is editing a copy."
  n=0; errors=""; any=0
  while IFS= read -r row; do
    [ -n "$row" ] || continue
    [ "$(field "$row" 2)" = "cron" ] || continue
    any=1; n=$((n + 1))
    cfg=$(field "$row" 0); cron=$(field "$row" 3); tz=$(field "$row" 4)
    chain=$(field "$row" 6); prompt=$(field "$row" 7); role=$(field "$row" 8); err=$(field "$row" 9)
    relcfg=$(rel_to_root "$cfg")
    if [ "$err" != "-" ]; then
      errors="${errors}  \"$relcfg\",\"refused\",\"$err\"
"; continue
    fi
    if [ "$chain" = "-" ] || [ "$prompt" = "-" ]; then
      errors="${errors}  \"$relcfg\",\"refused\",\"mode cron names no chain/prompt — a row would launch nothing\"
"; continue
    fi
    shape=$(scheduler_shape "$cron" "$tz")
    shape_rc=$?
    if [ "$shape_rc" != 0 ]; then
      errors="${errors}  \"$relcfg\",\"refused\",\"cron '$cron' cannot become a row: $shape\"
"; continue
    fi
    block="${block}
@${role} ${shape} bin/time/event-trigger.sh --run ${relcfg}"
  done <<EOF
$rows
EOF
  block="${block}
${END_MARK}"

  if [ "$any" = 0 ]; then
    # No config asks for the clock. If a previous install left a managed block,
    # withdraw it — a trigger that was turned off must not keep firing.
    if [ -r "$CRON_FILE" ] && grep -qF -- "$BEGIN_MARK" "$CRON_FILE"; then
      if [ "$DRY" = 1 ]; then
        printf 'cron[1]{config,row,state}:\n  "%s","(managed block)","would-withdraw"\n' "$CRON_FILE"
        exit 0
      fi
      tmp=$(mktemp "${CRON_FILE}.XXXXXX") || exit 1
      awk -v b="$BEGIN_MARK" -v e="$END_MARK" '
        $0 == b {inblock = 1; next}
        $0 == e {inblock = 0; next}
        inblock {next}
        {print}
      ' "$CRON_FILE" >"$tmp"
      mv "$tmp" "$CRON_FILE"
      printf 'cron[1]{config,row,state}:\n  "%s","(managed block)","withdrawn"\n' "$CRON_FILE"
      exit 0
    fi
    printf 'cron[0]{config,row,state}:\n  "-","-","no config declares trigger.mode: cron — nothing to install"\n'
    exit 0
  fi

  if [ ! -r "$CRON_FILE" ] && [ "$CREATE" != 1 ]; then
    printf 'event-trigger: no schedule at %s — the shipped example is running instead. Copy it first:\n  cp config/cron.yaml.example %s\n' \
      "$CRON_FILE" "$CRON_FILE" >&2
    exit 1
  fi

  mkdir -p "$(dirname "$CRON_FILE")" 2>/dev/null || true
  [ -r "$CRON_FILE" ] || : >"$CRON_FILE"

  current=$(awk -v b="$BEGIN_MARK" -v e="$END_MARK" '
    $0 == b {inblock = 1; print; next}
    $0 == e {inblock = 0; print; next}
    inblock {print}
  ' "$CRON_FILE")

  if [ "$DRY" = 1 ]; then
    printf 'cron[%s]{config,row,state}:\n%s  "%s","(managed block)","would-write"\n' \
      "$((n + 1))" "$errors" "$CRON_FILE"
    printf '%s\n' "$block"
    exit 0
  fi

  state="written"
  if [ "$current" = "$block" ]; then
    state="unchanged"
  else
    tmp=$(mktemp "${CRON_FILE}.XXXXXX") || exit 1
    awk -v b="$BEGIN_MARK" -v e="$END_MARK" '
      $0 == b {inblock = 1; next}
      $0 == e {inblock = 0; next}
      inblock {next}
      {print}
    ' "$CRON_FILE" >"$tmp"
    # The managed block always sits LAST, so a second run strips it from exactly
    # where it put it and the operator's own rows are never reordered.
    [ -s "$tmp" ] && [ -n "$(tail -c 1 "$tmp")" ] && printf '\n' >>"$tmp"
    printf '%s\n' "$block" >>"$tmp"
    mv "$tmp" "$CRON_FILE"
  fi

  printf 'cron[%s]{config,row,state}:\n%s  "%s","(managed block)","%s"\n' "$((n + 1))" "$errors" "$CRON_FILE" "$state"
  printf '# the scheduler reads it at start: bin/time/nornir-cron-start.sh --stop && bin/time/nornir-cron-start.sh\n'
  [ -n "$errors" ] && exit 1
  exit 0
fi

# ── --run <config>: the road a cron row takes ─────────────────────────────────
if [ -n "$RUN_CONFIG" ]; then
  case "$RUN_CONFIG" in /*) cfg=$RUN_CONFIG ;; *) cfg="$ROOT/$RUN_CONFIG" ;; esac
  if [ ! -r "$cfg" ]; then
    printf 'event-trigger: config "%s" is not readable\n' "$RUN_CONFIG" >&2
    exit 1
  fi
  row=$(python3 "$RESOLVER" one "$cfg") || exit 1
  mode=$(field "$row" 2); chain=$(field "$row" 6); prompt=$(field "$row" 7)
  role=$(field "$row" 8); err=$(field "$row" 9); root=$(field "$row" 1)
  if [ "$err" != "-" ]; then
    printf 'trigger[1]{config,state,detail}:\n  "%s","refused","%s"\n' "$RUN_CONFIG" "$err" >&2
    exit 1
  fi
  if [ "$mode" != "cron" ]; then
    printf 'trigger[1]{config,state,detail}:\n  "%s","refused","mode is %s — a cron row for a smithy that does not name cron"\n' "$RUN_CONFIG" "$mode" >&2
    exit 1
  fi
  if [ "$chain" = "-" ] || [ "$prompt" = "-" ]; then
    printf 'trigger[1]{config,state,detail}:\n  "%s","refused","the trigger names no chain/prompt"\n' "$RUN_CONFIG" >&2
    exit 1
  fi
  said=$(launch "$cfg" "$root" "$chain" "$prompt" "$role" "" cron)
  rc=$?
  state=$(field "$said" 0); detail=$(field "$said" 1)
  if [ "$rc" != 0 ]; then
    printf 'trigger[1]{config,state,detail}:\n  "%s","%s","%s"\n' "$RUN_CONFIG" "$state" "$detail" >&2
    exit 1
  fi
  printf 'trigger[1]{config,event,state,detail}:\n  "%s","-","%s","%s"\n' "$RUN_CONFIG" "$state" "$detail"
  exit 0
fi

# ── the event: every smithy that claims it, launched once each ────────────────
rows=$(scan_rows) || exit 1

faults=""
while IFS= read -r row; do
  [ -n "$row" ] || continue
  err=$(field "$row" 9)
  [ "$err" = "-" ] || faults="${faults}  \"$(rel_to_root "$(field "$row" 0)")\",\"$err\"
"
done <<EOF
$rows
EOF

if [ -n "$faults" ]; then
  printf 'smithies[%s]{config,fault}:\n%s' "$(printf '%s' "$faults" | grep -c .)" "$faults" >&2
  printf 'event-trigger: refusing to start anything while a config is misread\n' >&2
  exit 1
fi

reports=""; failed=0
while IFS= read -r row; do
  [ -n "$row" ] || continue
  [ "$(field "$row" 2)" = "event" ] || continue
  [ "$(field "$row" 5)" = "$EVENT" ] || continue
  cfg=$(field "$row" 0); root=$(field "$row" 1)
  chain=$(field "$row" 6); prompt=$(field "$row" 7); role=$(field "$row" 8)
  relcfg=$(rel_to_root "$cfg")
  if [ "$chain" = "-" ] || [ "$prompt" = "-" ]; then
    reports="${reports}  \"$relcfg\",\"$EVENT\",\"refused\",\"the trigger names no chain/prompt\"
"
    failed=1; continue
  fi
  said=$(launch "$cfg" "$root" "$chain" "$prompt" "$role" "$EVENT" event)
  rc=$?
  state=$(field "$said" 0); detail=$(field "$said" 1)
  [ "$rc" = 0 ] || failed=1
  reports="${reports}  \"$relcfg\",\"$EVENT\",\"$state\",\"$detail\"
"
done <<EOF
$rows
EOF

if [ -z "$reports" ]; then
  # A named refusal, never silence: the event, and the events that ARE claimed.
  claimed=$(printf '%s\n' "$rows" | while IFS= read -r row; do
    [ -n "$row" ] || continue
    [ "$(field "$row" 2)" = "event" ] || continue
    printf '%s\n' "$(field "$row" 5)"
  done | grep -v '^$' | sort -u | paste -sd, -)
  printf 'event-trigger[1]{event,state,claimed_events}:\n  "%s","no smithy claims this event","%s"\n' \
    "$EVENT" "${claimed:-none}" >&2
  exit 1
fi

printf 'trigger[%s]{config,event,state,detail}:\n%s' "$(printf '%s' "$reports" | grep -c .)" "$reports"
[ "$failed" = 0 ] || exit 1
exit 0
